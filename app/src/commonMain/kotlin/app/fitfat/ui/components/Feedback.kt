package app.fitfat.ui.components

/**
 * Тактильный и звуковой отклик барабанов, линеек и свайпов — как в макетах (DESIGN.md, «Движение и отклик»):
 * шаг — тихий глухой щелчок + короткая вибрация; упор в край — более низкий «тук» + сильная вибрация.
 * Уважает настройку «Звук и вибрация колеса». Реализация — платформенная.
 */
expect object Feedback {
    /** Шаг значения. */
    fun tick()
    /** Шаг барабана, линейки, круга веса: тот же щелчок, вибрация вполсилы. */
    fun step()
    /** Шаг без звука — только короткая вибрация (навбар). */
    fun tickSilent()
    /** Упор в край, срыв свайпа и прочие «сильные» моменты. */
    fun bump()
    /** Лёгкий отклик без звука — касание, открытие. */
    fun light()
}
