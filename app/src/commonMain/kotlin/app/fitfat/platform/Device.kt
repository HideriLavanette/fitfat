package app.fitfat.platform

/**
 * Телефон для сервера (DESIGN.md, «Подписка и доступ», «Отчёты о сбоях»). [id] не меняется при переустановке
 * приложения и смене аккаунта — к нему привязана пробная неделя ассистента; на Android — ANDROID_ID приложения,
 * на iOS — identifierForVendor. [info] — модель и версия системы для отчётов.
 */
expect object Device {
    val id: String
    val info: String
}

/** Сохранённое при падении (файл, записанный синхронно в обработчике); при следующем запуске уходит на сервер. */
expect object CrashStore {
    /** Поставить перехват падений. Вызывать один раз при старте. */
    fun install()
    /** Забрать сохранённый отчёт и стереть его; null — падений не было. */
    fun take(): String?
}
